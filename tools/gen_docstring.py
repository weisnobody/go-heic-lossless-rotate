"""Regenerate cli/docstring.go from the pinned upstream cli.py docstring.

Usage (from the repo root, after `make upstream`):
    python3 -I tools/gen_docstring.py .upstream/src/heic_rotate/cli.py > cli/docstring.go
"""
import ast
import json
import sys

src = open(sys.argv[1], encoding='utf-8').read()
doc = ast.get_docstring(ast.parse(src), clean=False)
print('// Code generated by tools/gen_docstring.py from upstream heic_rotate/cli.py. DO NOT EDIT.')
print()
print('package cli')
print()
print('// upstreamDocstring is cli.py\'s module docstring, which upstream uses as')
print('// the top-level -h description (argparse substitutes %(prog)s).')
print('const upstreamDocstring = ' + json.dumps(doc, ensure_ascii=False))
